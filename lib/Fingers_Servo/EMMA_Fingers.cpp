/* ════════════════════════════════════════════════════════════════
 *  set_note
 *  ----------------------------------------------------------------
 *  Считает дельту до заданной ноты и запускает каретку.
 *  Подъём и нажатие пальца — забота вызывающего кода.
 * ════════════════════════════════════════════════════════════════ */

void set_note(int nota, long* notes) {
    if (nota < 1 || nota > _notes_count) {
        Serial.println("[FINGERS] ERROR: Invalid note!");
        return;
    }

    _active_finger = get_finger_for_note(nota);
    long target_pos = notes[nota - 1];
    _pending_delta  = target_pos - _finger_pos[_active_finger];

    if (_pending_delta != 0) {
        bool dir = (_pending_delta < 0);
        //stepper_move(abs(_pending_delta), dir, 25000, 2500, 300, 300);
        
        
        //stepper_move(abs(_pending_delta), dir, 14000, 1900, 200, 70);
        stepper_move(abs(_pending_delta), dir, 12000, 1900, 200, 150);

        _moving = true; 
    } else {
        _moving = false;
    }
}


/* ════════════════════════════════════════════════════════════════
 *  fingers_update
 *  ----------------------------------------------------------------
 *  Отслеживает завершение движения каретки и синхронно сдвигает
 *  координаты всех пальцев на пройденную дельту.
 * ════════════════════════════════════════════════════════════════ */

void fingers_update() {
    if (_moving) {
        if (stepper_is_ready()) {
            // Каретка одна — сдвигаем координаты всех пальцев
            for (int i = 0; i < 4; i++) {
                _finger_pos[i] += _pending_delta;
            }
            _moving = false;
        }
    }
}


/* ════════════════════════════════════════════════════════════════
 *  fingers_are_busy
 *  ----------------------------------------------------------------
 *  Возвращает true, если каретка в движении.
 * ════════════════════════════════════════════════════════════════ */

bool fingers_are_busy() {
    return _moving;
}


/* ════════════════════════════════════════════════════════════════
 *  get_active_finger
 *  ----------------------------------------------------------------
 *  Возвращает индекс пальца текущей ноты.
 * ════════════════════════════════════════════════════════════════ */

int get_active_finger() {
    return _active_finger;
}
