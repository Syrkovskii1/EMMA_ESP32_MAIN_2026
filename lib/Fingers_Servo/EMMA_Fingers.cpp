/* ════════════════════════════════════════════════════════════════
 *  EMMA Fingers
 *  ----------------------------------------------------------------
 *  Логика управления кареткой с 4 пальцами скрипача.
 *
 *  Хранит абсолютные координаты пальцев в шагах мотора,
 *  по номеру ноты вычисляет нужную дельту и запускает каретку.
 *  Подъём и нажатие пальцев — забота вызывающего кода.
 * ════════════════════════════════════════════════════════════════ */

#include "EMMA_Fingers.h"
#include "EMMA_Stepper_Motor.h"

extern void activate_finger(int index);

/* ─── Состояние пальцев ───────────────────────────────────────── */

static long _finger_pos[4] = {0, 0, 0, 0};   // Абсолютные координаты 4 пальцев (шаги)
static int  _notes_count   = 0;              // Количество нот в раскладке

/* ─── Состояние движения ──────────────────────────────────────── */

static bool _moving        = false;          // Каретка в движении
static long _pending_delta = 0;              // Дельта текущего перемещения (шаги)
static int  _active_finger = -1;             // Палец, обслуживающий текущую ноту


/* ════════════════════════════════════════════════════════════════
 *  get_finger_for_note
 *  ----------------------------------------------------------------
 *  Возвращает индекс пальца (0..3), обслуживающего заданную ноту.
 * ════════════════════════════════════════════════════════════════ */

int get_finger_for_note(int nota) {
    switch (nota) {
        case 1: return 0;   // Note 1 (18mm)  -> Index
        case 2: return 0;   // Note 2 (35mm)  -> Index
        case 3: return 1;   // Note 3 (52mm)  -> Middle
        case 4: return 1;   // Note 4 (66mm)  -> Middle
        case 5: return 2;   // Note 5 (80mm)  -> Ring
        case 6: return 3;   // Note 6 (94mm)  -> Pinky
        case 7: return 3;   // Note 7 (110mm) -> Pinky
        default: return 0;  // Защита от мусора
    }
}


/* ════════════════════════════════════════════════════════════════
 *  fingers_init
 *  ----------------------------------------------------------------
 *  Переводит координаты нот из миллиметров в шаги мотора.
 *  Вызывается один раз при старте.
 * ════════════════════════════════════════════════════════════════ */

void fingers_init(long* notes, int notes_count, int pulses_per_mm) {
    _notes_count = notes_count;
    for (int i = 0; i < notes_count; i++) {
        notes[i] *= pulses_per_mm;
    }
}


/* ════════════════════════════════════════════════════════════════
 *  fingers_set_home
 *  ----------------------------------------------------------------
 *  Фиксирует физические домашние позиции пальцев после калибровки.
 * ════════════════════════════════════════════════════════════════ */


 void fingers_set_home(long* phys_pos) {
    // Просто записываем 4 физические координаты пальцев
    _finger_pos[0] = phys_pos[0];
    _finger_pos[1] = phys_pos[1];
    _finger_pos[2] = phys_pos[2];
    _finger_pos[3] = phys_pos[3];
}
